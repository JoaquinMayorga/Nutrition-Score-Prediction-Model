import streamlit as st

st.title("Nutrition Score Prediction")

"""How this project works is a food item is given a score from 0 to 4 based on the ingredients you input. 0 is the best while 4 is the worst."""

st.sidebar.header("Enter Food Metrics")

def get_user_input():
    # Numerical inputs
    energy = st.sidebar.number_input("Energy (kcal)", value=25.0)
    fat = st.sidebar.number_input("Fat (100g)", value=5.0)
    sat_fat = st.sidebar.number_input("Saturated Fat (100g)", value=3.0)
    carbs = st.sidebar.number_input("Carbs (100g)", value=60.0)
    sugars = st.sidebar.number_input("Sugars (100g)", value=20.0)
    fiber = st.sidebar.number_input("Fiber (100g)", value=10.0)
    proteins = st.sidebar.number_input("Proteins (100g)", value=40.0)
    salt = st.sidebar.number_input("Salt (100g)", value=0.0)
    sodium = st.sidebar.number_input("Sodium (100g)", value=12.0)

    # Categorical input (Dairy)
    dairy_option = st.sidebar.selectbox("Contains Dairy?", ("Yes", "No"))
    dairy_val = 1 if dairy_option == "Yes" else 0

    # Create the dictionary
    data = {
        'energy_kcal': energy,
        'fat_100g': fat,
        'saturated_fat_100g': sat_fat,
        'carbs_100g': carbs,
        'sugars_100g': sugars,
        'fiber_100g': fiber,
        'proteins_100g': proteins,
        'salt_100g': salt,
        'sodium_100g': sodium,
        'contains_dairy': dairy_val
    }

    # Wrap in a list for the DataFrame
    return pd.DataFrame(data, index=[0])

# Store the input in a variable
