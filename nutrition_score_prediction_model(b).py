with st.form("nutrition_form"):
    st.subheader("Input Food Details")

    # Using columns to make the UI look cleaner
    col1, col2 = st.columns(2)

    with col1:
        energy = st.number_input("Energy (kcal)", min_value=0.0, value=25.0)
        fat = st.number_input("Fat (100g)", min_value=0.0, value=5.0)
        sat_fat = st.number_input("Saturated Fat (100g)", min_value=0.0, value=3.0)
        carbs = st.number_input("Carbs (100g)", min_value=0.0, value=60.0)
        sugars = st.number_input("Sugars (100g)", min_value=0.0, value=20.0)

    with col2:
        fiber = st.number_input("Fiber (100g)", min_value=0.0, value=10.0)
        proteins = st.number_input("Proteins (100g)", min_value=0.0, value=40.0)
        salt = st.number_input("Salt (100g)", min_value=0.0, value=0.0)
        sodium = st.number_input("Sodium (100g)", min_value=0.0, value=12.0)
